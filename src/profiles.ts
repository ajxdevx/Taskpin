import { packToMarkdown } from "./pack.js";
import type { ContextPack } from "./types.js";

export type OutputProfile = "default" | "cursor" | "claude" | "copilot";

const PROFILE_ALIASES: Record<string, OutputProfile> = {
  default: "default",
  markdown: "default",
  cursor: "cursor",
  claude: "claude",
  anthropic: "claude",
  copilot: "copilot",
  github: "copilot",
  "github-copilot": "copilot",
};

export function resolveOutputProfile(name?: string): OutputProfile {
  if (!name || !name.trim()) return "default";
  const key = name.trim().toLowerCase();
  return PROFILE_ALIASES[key] ?? "default";
}

function fenceLang(filePath: string): string {
  const ext = filePath.split(".").pop()?.toLowerCase() ?? "";
  const map: Record<string, string> = {
    ts: "typescript",
    tsx: "tsx",
    js: "javascript",
    jsx: "jsx",
    mjs: "javascript",
    cjs: "javascript",
    json: "json",
    md: "markdown",
    yaml: "yaml",
    yml: "yaml",
    py: "python",
    rs: "rust",
    go: "go",
    sh: "bash",
    astro: "astro",
    vue: "vue",
    svelte: "svelte",
    css: "css",
    scss: "scss",
    html: "html",
  };
  return map[ext] ?? "";
}

function indexTable(pack: ContextPack): string[] {
  const lines = [
    `| File | Why | score | form | ~tokens |`,
    `| --- | --- | ---: | --- | ---: |`,
  ];
  for (const f of pack.files) {
    const form = f.presentation === "full" ? "—" : f.presentation;
    lines.push(
      `| \`${f.path}\` | ${f.reasons.join(", ")} | ${f.score} | ${form} | ${f.tokens} |`,
    );
  }
  return lines;
}

function omittedSection(pack: ContextPack): string[] {
  if (!pack.omitted?.length) return [];
  const lines = [
    ``,
    `### Omitted (receipts)`,
    ``,
    `| File | score | why omitted |`,
    `| --- | ---: | --- |`,
  ];
  for (const o of pack.omitted) {
    const detail = o.detail ? ` — ${o.detail}` : "";
    lines.push(`| \`${o.path}\` | ${o.score} | ${o.omit}${detail} |`);
  }
  return lines;
}

function blockedSection(pack: ContextPack): string[] {
  if (!pack.blockedSecrets?.length) return [];
  const lines = [``, `### Blocked (secrets)`, ``];
  for (const b of pack.blockedSecrets) {
    lines.push(`- \`${b.path}\` — ${b.kinds.join(", ")}`);
  }
  return lines;
}

function packToCursor(pack: ContextPack): string {
  const lines = [
    `# Taskpin context`,
    ``,
    `**Task:** ${pack.task}`,
    `**Budget:** ~${pack.usedTokens} / ${pack.budgetTokens} tokens`,
    ``,
    `Pin or reference these paths:`,
  ];
  for (const f of pack.files) {
    lines.push(`- \`${f.path}\` — ${f.reasons.join(", ")}`);
  }
  lines.push(``, `---`, ``);
  for (const f of pack.files) {
    const lang = fenceLang(f.path);
    const tag =
      f.presentation !== "full" ? ` (${f.presentation})` : "";
    lines.push(`## ${f.path}${tag}`, ``);
    lines.push("```" + lang, f.content, "```", ``);
  }
  return lines.join("\n");
}

function packToClaude(pack: ContextPack): string {
  const lines = [
    `<taskpin_context`,
    `  schema_version="${pack.schema_version ?? "1.0"}"`,
    `  task="${pack.task.replace(/"/g, "&quot;")}"`,
    `  budget_tokens="${pack.budgetTokens}"`,
    `  used_tokens="${pack.usedTokens}"`,
    `>`,
    `<summary>`,
    `Repository root: ${pack.root}`,
    `Files included: ${pack.files.length}`,
    `</summary>`,
    `<index>`,
    ...indexTable(pack),
    `</index>`,
  ];
  lines.push(...omittedSection(pack));
  for (const f of pack.files) {
    const form =
      f.presentation !== "full" ? ` presentation="${f.presentation}"` : "";
    lines.push(
      `<file path="${f.path}" score="${f.score}" reasons="${f.reasons.join(",")}"${form}>`,
      f.content,
      `</file>`,
    );
  }
  lines.push(`</taskpin_context>`);
  return lines.join("\n");
}

function packToCopilot(pack: ContextPack): string {
  const lines = [
    `# Task context`,
    ``,
    `Generated by taskpin for GitHub Copilot / IDE chat.`,
    ``,
    `**Task:** ${pack.task}`,
    `**Tokens:** ~${pack.usedTokens} of ${pack.budgetTokens}`,
    ``,
    `## Files in this pack`,
    ``,
    ...indexTable(pack),
    ...omittedSection(pack),
    ...blockedSection(pack),
    ``,
    `---`,
    ``,
  ];
  for (const f of pack.files) {
    const lang = fenceLang(f.path);
    lines.push(`# File: ${f.path}`, ``);
    lines.push("```" + lang, f.content, "```", ``);
  }
  return lines.join("\n");
}

export function packToProfileMarkdown(
  pack: ContextPack,
  profile: OutputProfile,
): string {
  switch (profile) {
    case "cursor":
      return packToCursor(pack);
    case "claude":
      return packToClaude(pack);
    case "copilot":
      return packToCopilot(pack);
    default:
      return packToMarkdown(pack);
  }
}

export function renderPackOutput(
  pack: ContextPack,
  format: string,
  profile: OutputProfile,
): string {
  if (format === "json") {
    const body = {
      ...pack,
      output_profile: profile === "default" ? undefined : profile,
    };
    return JSON.stringify(body, null, 2);
  }
  return packToProfileMarkdown(pack, profile);
}
